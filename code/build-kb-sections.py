#!/usr/bin/env python3
"""Split knowledge-base/*.md into one file per section and write knowledge-base/index.md.

AI agents fetch the knowledge base from raw GitHub, which can only serve whole files (up to 400 KB).
The skills cite sections as `<file> "<Heading>"`; this makes every cited heading its own small file,
listed in knowledge-base/index.md, so an agent fetches only the section it needs.

Rules: headings of level 1-3 outside code fences are sections. A section whose text (with its
subsections) fits in MAX_SECTION bytes is written whole and its subsections stay inside it; a larger
one is written as its own text plus links, and each subsection gets its own file.

Run from the repo root:  python3 code/build-kb-sections.py          (writes)
                         python3 code/build-kb-sections.py --check  (exits 1 if out of date)
"""
import os
import re
import shutil
import sys

KB = 'knowledge-base'
OUT = os.path.join(KB, 'sections')
INDEX = os.path.join(KB, 'index.md')
RAW = 'https://raw.githubusercontent.com/Walkover-Web-Solution/viasocket-developer-hub-skills/refs/heads/main'
MAX_SECTION = 24_000
MAX_LEVEL = 3
GENERATED = '<!-- Generated by code/build-kb-sections.py from knowledge-base/{src}. Edit the source file, not this one. -->\n'

# One line per file: what it is for. A new KB file without a line here still gets split, with an empty summary.
SUMMARIES = {
    'dh-knowledgebase.md': 'Consolidated KB for plugs, actions and triggers: design, UX, fields, naming, code, runtime, review. Read in full.',
    'dh-connection-kb.md': 'Consolidated KB for connections (auth): selection, payloads, DH URLs. Read in full.',
    'dh-Input-fields-json-builder.md': 'Exact JSON schema of every input field type (static and dynamic).',
    'perform-code.md': 'Perform-code rules for actions and every trigger type, with examples.',
    'ux-practice.md': 'Input-field UX rules by action category and trigger type.',
    'ux-worked-examples.md': 'Worked input-field designs for real apps.',
    'dh-connection-practice.md': 'How to build each auth type (OAuth 2.0, API key, Basic, OAuth 1.0).',
    'dh-connection-schema.md': 'Exact create/update JSON schema of each auth type.',
    'dh-connection-examples.md': 'Complete connection examples for real apps.',
    'dh-database-schema.md': 'Developer Hub tables and columns.',
    'plug-review.md': 'Review test cases for a plug.',
    'backed-plug-service.md': 'Backend plug service: one webhook per app, instant-trigger plumbing.',
    'viasocket-flow-execution-script.md': 'How a flow step executes in the VM.',
}
READ_IN_FULL = ('dh-knowledgebase.md', 'dh-connection-kb.md')


def slugify(text):
    s = re.sub(r'[`*_~]', '', text).lower()
    s = re.sub(r'[^a-z0-9]+', '-', s).strip('-')
    return s[:80].rstrip('-') or 'section'


def parse(text):
    """Return the root node: {title, level, start, end, children} over the file's lines."""
    lines = text.split('\n')
    heads = []
    fence = None
    for i, line in enumerate(lines):
        m = re.match(r'^\s*(```|~~~)', line)
        if m:
            fence = None if fence == m.group(1) else (fence or m.group(1))
            continue
        if fence:
            continue
        h = re.match(r'^(#{1,6})\s+(.+?)\s*#*\s*$', line)
        if h and len(h.group(1)) <= MAX_LEVEL:
            heads.append((len(h.group(1)), h.group(2).strip(), i))
    root = {'title': None, 'level': 0, 'start': 0, 'end': len(lines), 'children': []}
    stack = [root]
    for level, title, i in heads:
        while stack[-1]['level'] >= level:
            stack.pop()
        node = {'title': title, 'level': level, 'start': i, 'end': None, 'children': []}
        stack[-1]['children'].append(node)
        stack.append(node)

    def close(node, end):
        node['end'] = end
        for j, child in enumerate(node['children']):
            close(child, node['children'][j + 1]['start'] if j + 1 < len(node['children']) else end)

    close(root, len(lines))
    return root, lines


def build_file(src):
    """Write the sections of one KB file; return the index lines for it."""
    text = open(os.path.join(KB, src), encoding='utf-8').read()
    root, lines = parse(text)
    stem = src[:-3]
    used = set()
    out_lines = []

    def body(node, start=None, end=None):
        return '\n'.join(lines[node['start'] if start is None else start:node['end'] if end is None else end]).strip('\n')

    def path_for(node, parent_slug):
        slug = slugify(node['title'])
        if slug in used:
            slug = f'{parent_slug}--{slug}' if parent_slug else slug
        n, base = 2, slug
        while slug in used:
            slug, n = f'{base}-{n}', n + 1
        used.add(slug)
        return slug

    def walk(node):
        for c in node['children']:
            yield c
            yield from walk(c)

    def emit_all(node, parent_slug, depth):
        slug = path_for(node, parent_slug)
        rel = f'sections/{stem}/{slug}.md'
        whole = body(node)
        size = len(whole.encode('utf-8'))
        if size <= MAX_SECTION or not node['children']:
            write(rel, src, whole)
            inside = [c['title'] for c in walk(node)]
            note = f' — also covers: {"; ".join(inside)}' if inside else ''
            out_lines.append(f'{"  " * depth}- [{node["title"]}]({rel}) · {kb(size)}{note}')
            return rel
        intro = body(node, end=node['children'][0]['start'])
        out_lines.append(f'{"  " * depth}- [{node["title"]}]({rel}) · {kb(size)} in all, split:')
        child_links = []
        for child in node['children']:
            child_rel = emit_all(child, slug, depth + 1)
            child_links.append(f'- [{child["title"]}]({RAW}/{KB}/{child_rel})')
        write(rel, src, intro + '\n\n**Subsections — fetch only the one you need:**\n\n' + '\n'.join(child_links))
        return rel

    if root['children'] and root['children'][0]['start'] > 0:
        preamble = body(root, end=root['children'][0]['start']).strip()
    else:
        preamble = ''
    size = len(text.encode('utf-8'))
    head = f'### [{src}]({src}) · {kb(size)}'
    summary = SUMMARIES.get(src, '')
    entry = [head, '', summary] if summary else [head]
    if src in READ_IN_FULL or size <= MAX_SECTION:
        return entry + ['', '_Fetch the whole file._', '']
    if preamble and len(preamble.encode('utf-8')) > 200:
        write(f'sections/{stem}/_intro.md', src, preamble)
        out_lines.append(f'- [Intro](sections/{stem}/_intro.md) · {kb(len(preamble.encode("utf-8")))}')
    for child in root['children']:
        emit_all(child, '', 0)
    return entry + [''] + out_lines + ['']


def kb(n):
    return f'{max(1, round(n / 1000))} KB'


PENDING = {}


def write(rel, src, content):
    PENDING[os.path.join(KB, rel)] = GENERATED.format(src=src) + content.rstrip('\n') + '\n'


def main():
    check = '--check' in sys.argv
    files = sorted(f for f in os.listdir(KB) if f.endswith('.md') and f != 'index.md')
    index = [
        '# viaSocket Developer Hub knowledge base — index',
        '',
        GENERATED.format(src='*.md').strip(),
        '',
        f'Links are relative to `{RAW}/{KB}/` (prefix them to fetch).',
        '',
        'Every knowledge-base file, and for the large ones every section as its own small file. Skills cite a section as',
        '`<file> "<Heading>"`: find that heading below and fetch its link. Fetch raw and read the whole file you fetch',
        '(`curl -s <url>`, or a fetch that returns the text verbatim); a summarizing fetch loses the exact keys and schemas.',
        'A section whose subsections are listed after it is split: fetch the subsection you need, not the parent.',
        '',
    ]
    for src in files:
        index += build_file(src)
    PENDING[INDEX] = '\n'.join(index).rstrip('\n') + '\n'

    current = {}
    if os.path.isdir(OUT):
        for d, _, fs in os.walk(OUT):
            for f in fs:
                p = os.path.join(d, f)
                current[p] = open(p, encoding='utf-8').read()
    if os.path.exists(INDEX):
        current[INDEX] = open(INDEX, encoding='utf-8').read()
    if check:
        if current != PENDING:
            print('knowledge-base sections are out of date: run python3 code/build-kb-sections.py')
            sys.exit(1)
        print('knowledge-base sections are up to date')
        return
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    for p, content in PENDING.items():
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, 'w', encoding='utf-8').write(content)
    print(f'wrote {len(PENDING) - 1} section files and {INDEX}')


if __name__ == '__main__':
    main()
